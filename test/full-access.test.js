"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), "frst-full-"));
process.env.FS_DATA_DIR = dataDir;
const { state } = require("../src/state");
const settings = require("../src/settings");
const { createDesktopBackend } = require("../desktop/backend");
const { denialReason, runCommand } = require("../src/tools/command");
test.after(() => fs.rmSync(dataDir, { recursive: true, force: true }));
test("Full accès : confirmations forcées, commandes, persistance et retour au mode normal", async () => {
    const events = [];
    const backend = createDesktopBackend((...args) => events.push(args));
    require("../src/ui-bridge").setUiBackend(backend);
    assert.equal(state.fullAccess, false);
    assert.ok(denialReason("git", ["push"]));
    settings.save({ fullAccessAlways: true });
    assert.equal(settings.load().fullAccessAlways, true);
    state.fullAccess = true;
    state.workspace = dataDir;
    assert.equal(await backend.confirm("action", { force: true }), true);
    assert.equal(await backend.askCommand("commande", "cmd"), "o");
    assert.equal(events.length, 0);
    assert.equal(backend.status().fullAccess, true);
    assert.equal(denialReason("git", ["push"]), null);
    const result = await runCommand({ timeout_ms: 10000, command: process.platform === "win32" ? 'Write-Output FULL_ACCESS_OK' : 'echo FULL_ACCESS_OK' });
    assert.equal(result.exit_code, 0);
    assert.match(result.output, /FULL_ACCESS_OK/);
    state.fullAccess = false;
    settings.save({ fullAccessAlways: false });
    assert.ok(denialReason("git", ["push"]));
    assert.equal(settings.load().fullAccessAlways, false);
    const pending = backend.confirm("confirmer");
    const prompt = events.find(([name]) => name === "prompt")[1];
    backend.resolvePrompt(prompt.id, "n");
    assert.equal(await pending, false);
    const waiting = backend.confirm("action en attente", { force: true });
    const question = backend.ask("information indispensable");
    state.fullAccess = true;
    backend.approvePendingActions();
    assert.equal(await waiting, true);
    const questionPrompt = events.filter(([name]) => name === "prompt").at(-1)[1];
    assert.equal(questionPrompt.kind, "ask");
    assert.equal(backend.resolvePrompt(questionPrompt.id, "réponse"), true);
    assert.equal(await question, "réponse");
    state.fullAccess = false;
});
