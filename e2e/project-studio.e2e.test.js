"use strict";
/* global openFile, code, currentTab, readStudioBookmarks */
const test=require("node:test"),assert=require("node:assert/strict"),fs=require("node:fs"),os=require("node:os"),path=require("node:path");
const {_electron}=require("playwright-core"),electron=require("electron"),root=path.resolve(__dirname,"..");
test("e2e : cockpit, commande réelle, formatage, comparaison, aperçu isolé et préférences",{timeout:90000},async()=>{
    const dir=fs.mkdtempSync(path.join(os.tmpdir(),"frst-studio-e2e-")),project=path.join(dir,"project");fs.mkdirSync(project);
    fs.writeFileSync(path.join(project,"package.json"),JSON.stringify({name:"atelier-interface",description:"Un projet de démonstration pour le cockpit.",scripts:{test:"node task.cjs",dev:"node task.cjs"},devDependencies:{typescript:"1",vite:"1"}}));
    fs.writeFileSync(path.join(project,"task.cjs"),'console.log("STUDIO_TASK_E2E_OK");');
    fs.writeFileSync(path.join(project,"app.js"),"const value={a:1}\n");
    fs.writeFileSync(path.join(project,"README.md"),"# Atelier\n\nUne documentation **claire**.\n\n| Fonction | État |\n| --- | --- |\n| Aperçu | Prêt |\n\n<script>window.MARKDOWN_PWNED=true</script><img src=x onerror=alert(1)>\n");
    fs.writeFileSync(path.join(project,"index.html"),"<!doctype html><html><head><link rel='stylesheet' href='./style.css'></head><body><h1 id='greet'>Avant</h1><script>document.getElementById('greet').textContent='PREVIEW_SCRIPT_OK'</script></body></html>");
    fs.writeFileSync(path.join(project,"style.css"),"h1{color:rgb(0,120,212)}");
    fs.writeFileSync(path.join(project,"image.png"),Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLbtAAAAABJRU5ErkJggg==","base64"));
    fs.writeFileSync(path.join(project,"data.bin"),Buffer.from([0,1,255,4]));
    fs.writeFileSync(path.join(project,"unicode.txt"),Buffer.from("\uFEFFÉté UTF16\r\n","utf16le"));
    const harness=path.join(dir,"launch.cjs");
    fs.writeFileSync(harness,`const {app}=require('electron');app.setPath('userData',${JSON.stringify(path.join(dir,"electron"))});const session=require(${JSON.stringify(path.join(root,"src/core/session"))});session.bootstrap=async()=>({ok:true});require(${JSON.stringify(path.join(root,"src/api/api"))}).requestModel=async()=>"Résumé QA";require(${JSON.stringify(path.join(root,"src/api/agents"))}).listAgents=async()=>({agents:[{id:-1002,name:'GPT 6 Luna'}],source:'local'});require(${JSON.stringify(path.join(root,"desktop/main.js"))});`);
    const env={...process.env,FS_DATA_DIR:dir,FS_STATE_DIR:dir,ELECTRON_DISABLE_SECURITY_WARNINGS:"1"};delete env.ELECTRON_RUN_AS_NODE;
    const app=await _electron.launch({executablePath:electron,args:[harness],env,cwd:root,timeout:30000});
    try{
        const page=await app.firstWindow(),errors=[];page.on("pageerror",error=>errors.push(error.message));
        await page.waitForFunction(async()=>(await window.frst.status()).booted);
        await page.evaluate(project=>window.frst.openProject(project),project);
        await page.locator('[data-view="project"]').click();
        await page.waitForFunction(()=>document.getElementById("studio-project-name").textContent==="atelier-interface");
        assert.match(await page.locator("#studio-stack").innerText(),/Vite/);
        await page.evaluate(()=>openFile("app.js"));
        assert.equal(await page.evaluate(()=>document.getElementById("app").classList.contains("view-project")),false);
        await page.locator('[data-view="project"]').click();
        if(process.env.FRST_QA_SCREENSHOT)await page.screenshot({path:process.env.FRST_QA_SCREENSHOT.replace(/\.png$/,"-overview.png")});
        await page.locator('[data-studio-tab="tasks"]').click();
        await page.locator('[data-task-id="package:test"]').getByRole("button",{name:"Exécuter",exact:true}).click();
        await page.waitForFunction(()=>document.getElementById("studio-log").textContent.includes("STUDIO_TASK_E2E_OK"));
        await page.waitForFunction(()=>document.getElementById("studio-log-meta").textContent.includes("Réussie"));
        await page.locator('[data-studio-tab="tools"]').click();
        await page.locator("#studio-tool-input").fill('{"a":1}');await page.locator("#studio-transform-run").click();
        assert.match(await page.locator("#studio-tool-output").inputValue(),/"a": 1/);
        await page.locator("#studio-transform").selectOption("base64-encode");await page.locator("#studio-tool-input").fill("Été QA");await page.locator("#studio-transform-run").click();
        const encoded=await page.locator("#studio-tool-output").inputValue();
        await page.locator("#studio-transform").selectOption("base64-decode");await page.locator("#studio-tool-input").fill(encoded);await page.locator("#studio-transform-run").click();
        assert.equal(await page.locator("#studio-tool-output").inputValue(),"Été QA");
        await page.locator("#studio-close").click();
        await page.evaluate(()=>openFile("app.js"));
        await page.locator("#studio-editor-toolbar").getByRole("button",{name:"Formater",exact:true}).click();
        await page.waitForFunction(()=>code.value.includes("const value ="));
        await page.locator("#studio-editor-toolbar").getByRole("button",{name:"Symboles",exact:true}).click();
        await page.waitForFunction(()=>document.getElementById("studio-symbol-list").textContent.includes("value"));
        await page.locator("#studio-symbol-close").click();
        await page.locator("#studio-editor-toolbar").getByRole("button",{name:"Comparer",exact:true}).click();
        await page.waitForSelector("#studio-merge-host .cm-mergeView");
        assert.match(await page.locator("#studio-compare-file").innerText(),/app.js/);
        if(process.env.FRST_QA_SCREENSHOT)await page.screenshot({path:process.env.FRST_QA_SCREENSHOT.replace(/\.png$/,"-compare.png")});
        await page.locator("#studio-compare-close").click();
        await page.keyboard.press("Control+F2");
        assert.equal(await page.evaluate(()=>readStudioBookmarks().length),1);
        await page.evaluate(()=>openFile("README.md"));
        await page.locator("#studio-editor-toolbar").getByRole("button",{name:"Aperçu",exact:true}).click();
        await page.waitForSelector("#studio-markdown-preview table");
        assert.equal(await page.locator("#studio-markdown-preview script, #studio-markdown-preview img").count(),0);
        assert.equal(await page.evaluate(()=>window.MARKDOWN_PWNED),undefined);
        if(process.env.FRST_QA_SCREENSHOT)await page.screenshot({path:process.env.FRST_QA_SCREENSHOT.replace(/\.png$/,"-markdown.png")});
        await page.evaluate(()=>openFile("index.html"));
        const frame=page.frameLocator("#studio-web-preview");await frame.locator("#greet").waitFor();
        assert.equal(await frame.locator("#greet").innerText(),"PREVIEW_SCRIPT_OK");
        const isolated=await frame.locator("body").evaluate(()=>({bridge:typeof window.frst,parentBlocked:(()=>{try{return !window.parent.document;}catch{return true;}})()}));
        assert.equal(isolated.bridge,"undefined");assert.equal(isolated.parentBlocked,true);
        await page.locator("#studio-preview-close").click();
        const originalBinary=fs.readFileSync(path.join(project,"data.bin"));
        await page.evaluate(()=>openFile("data.bin"));
        await page.waitForSelector("#studio-asset-view:not(.hidden)");
        assert.match(await page.locator("#studio-asset-view").innerText(),/lecture seule/);
        await page.keyboard.press("Control+s");
        assert.deepEqual(fs.readFileSync(path.join(project,"data.bin")),originalBinary);
        await page.evaluate(()=>openFile("image.png"));
        await page.waitForSelector("#studio-asset-view img");
        await page.evaluate(()=>openFile("unicode.txt"));
        assert.equal(await page.evaluate(()=>code.value),"Été UTF16\n");
        await page.keyboard.press("Control+s");
        await page.waitForTimeout(100);
        assert.equal(fs.readFileSync(path.join(project,"unicode.txt")).subarray(0,2).toString("hex"),"fffe");
        await page.locator('[data-view="project"]').click();
        await page.locator('[data-studio-tab="research"]').click();
        assert.equal(await page.locator("#studio-research-form").isVisible(),true);
        await page.locator('[data-view="settings"]').click();
        await page.locator("#settings-search").fill("apparence");
        await page.locator("#studio-font-size").fill("15");await page.locator("#studio-word-wrap").check();await page.locator("#studio-auto-save").check();await page.locator("#studio-format-save").check();
        await page.locator("#studio-editor-settings-save").click();
        await page.waitForFunction(async()=>(await window.frst.editorPreferences()).autoSave);
        await page.locator("#settings-search").fill("");await page.locator("#settings-close").click();
        await page.evaluate(()=>openFile("app.js"));
        await page.locator("#cm-host .cm-content").fill("const autosaved={ready:true}");
        await page.waitForFunction(()=>!currentTab().dirty&&currentTab().content.includes("const autosaved ="),null,{timeout:10000});
        assert.match(fs.readFileSync(path.join(project,"app.js"),"utf8"),/const autosaved =/);
        await page.keyboard.press("Control+p");await page.locator("#palette-input").fill("READMZ");
        await page.waitForFunction(()=>document.getElementById("palette-list").textContent.includes("README.md"));
        await page.keyboard.press("Escape");
        assert.deepEqual(errors,[]);
    }finally{await app.close();}
});
