"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { _electron } = require("playwright-core");
const electron = require("electron");
const root = path.resolve(__dirname, "..");

test("e2e : connexion guidée, erreur lisible, mot de passe effacé et première demande", { timeout: 60000 }, async () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "frst-guide-e2e-"));
    const project = path.join(dir, "mon-projet"); fs.mkdirSync(project);
    const harness = path.join(dir, "launch.cjs");
    fs.writeFileSync(harness, `
        const {app, dialog} = require('electron');
        app.setName('FRST connection guide test');
        app.setPath('userData', ${JSON.stringify(path.join(dir, "electron-data"))});
        global.qaConnected = false;
        global.qaMessages = [];
        const session = require(${JSON.stringify(path.join(root, "src/core/session"))});
        session.bootstrap = async options => {
            if (options.interactive !== false) throw new Error('Le bureau ne doit pas demander les identifiants dans le chat');
            return global.qaConnected ? {ok:true} : {ok:false, needsLogin:true};
        };
        session.handleInput = async prompt => {
            global.qaMessages.push(prompt);
            if (prompt === 'WAIT_FOR_LOGOUT_TEST') await new Promise(resolve => {global.qaRelease = resolve;});
            return {exit:false, completed:true};
        };
        require(${JSON.stringify(path.join(root, "src/api/login"))}).loginWithPassword = async ({email, password}) => {
            if (email !== 'test@example.org' || password !== 'FAKE_PASSWORD_QA') throw new Error('Mot de passe incorrect');
            global.qaConnected = true;
        };
        require(${JSON.stringify(path.join(root, "src/api/auth"))}).getAccessToken = async () => 'FAKE_TOKEN_QA';
        const authModule = require(${JSON.stringify(path.join(root, "src/api/auth"))});
        const realLogout = authModule.logout;
        authModule.logout = async () => { await realLogout(); global.qaConnected = false; };
        dialog.showOpenDialog = async () => ({canceled:false, filePaths:[${JSON.stringify(project)}]});
        require(${JSON.stringify(path.join(root, "desktop/main.js"))});
    `);
    const env = { ...process.env, FS_DATA_DIR: dir, FS_STATE_DIR: dir, ELECTRON_DISABLE_SECURITY_WARNINGS: "1" };
    delete env.ELECTRON_RUN_AS_NODE;
    const app = await _electron.launch({ executablePath: electron, args: [harness], cwd: root, env, timeout: 30000 });
    try {
        const page = await app.firstWindow();
        const errors = []; page.on("pageerror", error => errors.push(error.message));
        await page.waitForSelector("#connection-guide:not(.hidden)");
        assert.equal(await page.locator('#guide-email').getAttribute("type"), "email");
        assert.equal(await page.locator('#guide-password').getAttribute("type"), "password");
        assert.match(await page.locator('.guide-description').innerText(), /mêmes identifiants/);
        if (process.env.FRST_QA_SCREENSHOT) await page.screenshot({ path: process.env.FRST_QA_SCREENSHOT.replace(/\.png$/, "-login.png"), fullPage: true });
        await page.locator("#guide-email").fill("test@example.org");
        await page.locator("#guide-password").fill("BAD_QA_PASSWORD");
        await page.locator("#guide-login-submit").click();
        await page.waitForSelector("#guide-message.is-error");
        assert.match(await page.locator("#guide-message").innerText(), /Vérifie l’adresse e-mail/);
        assert.equal(await page.locator("#guide-password").inputValue(), "");
        assert.doesNotMatch(await page.locator("#transcript").innerText(), /BAD_QA_PASSWORD|test@example/);
        await page.locator("#guide-password").fill("FAKE_PASSWORD_QA");
        await page.locator("#guide-login-submit").click();
        await page.waitForFunction(() => document.getElementById("guide-title").textContent === "Ouvre le bon dossier");
        assert.equal(await page.locator("#guide-password").inputValue(), "");
        assert.equal((await page.evaluate(() => window.frst.status())).booted, true);
        await page.locator("#guide-pick-project").click();
        await page.waitForFunction(() => document.getElementById("guide-project-name").textContent.includes("mon-projet"));
        await page.locator("#guide-project-next").click();
        assert.match(await page.locator('[data-guide-page="3"]').innerText(), /s’empilent juste au-dessus/);
        await page.locator("#guide-first-prompt").click();
        await page.waitForSelector("#connection-guide.hidden", { state: "attached" });
        assert.match(await page.locator("#input").inputValue(), /Explore ce projet/);
        assert.deepEqual(await app.evaluate(() => global.qaMessages), []);
        const storage = await page.evaluate(() => JSON.stringify({ ...localStorage }));
        assert.doesNotMatch(storage, /FAKE_PASSWORD_QA|BAD_QA_PASSWORD/);
        await page.evaluate(() => { window.qaPending = window.frst.submit("WAIT_FOR_LOGOUT_TEST", []); });
        await page.waitForFunction(async () => (await window.frst.status()).busy);
        await page.locator('[data-view="settings"]').click();
        assert.equal(await page.locator("#settings-logout").isDisabled(), true);
        assert.match(await page.evaluate(() => window.frst.logoutAccount().catch(error => error.message)), /Arrête la tâche/);
        assert.equal((await page.evaluate(() => window.frst.status())).booted, true);
        await app.evaluate(() => global.qaRelease());
        await page.evaluate(() => window.qaPending);
        await page.evaluate(() => window.frst.taskQueue("add", {prompt:"À conserver après déconnexion"}));
        await page.waitForSelector("#settings-logout:enabled");
        await page.locator("#settings-logout").click();
        await page.waitForSelector("#connection-guide:not(.hidden)");
        assert.match(await page.locator("#guide-message").innerText(), /déconnecté/);
        assert.equal((await page.evaluate(() => window.frst.status())).booted, false);
        assert.equal(await page.locator("#guide-email").inputValue(), "");
        const queue = await page.evaluate(() => window.frst.taskQueue("list"));
        assert.equal(queue.enabled, false);
        assert.ok(queue.tasks.some(task => task.prompt === "À conserver après déconnexion"));
        assert.equal((await page.evaluate(() => window.frst.bootstrap())).needsLogin, true);
        await page.locator("#guide-email").fill("test@example.org");
        await page.locator("#guide-password").fill("FAKE_PASSWORD_QA");
        await page.locator("#guide-login-submit").click();
        await page.waitForFunction(() => document.getElementById("guide-title").textContent === "Ouvre le bon dossier");
        await page.locator("#guide-close").click();
        await page.evaluate(() => window.frst.submit("/logout", []));
        await page.waitForSelector("#connection-guide:not(.hidden)");
        assert.equal((await page.evaluate(() => window.frst.status())).booted, false);
        assert.deepEqual(errors, []);
    } finally { await app.close(); }
});
