"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const {_electron} = require("playwright-core");
const electron = require("electron");
const root = path.resolve(__dirname, "..");

test("e2e : bibliothèque, profils, marketplace, MCP réel et paramètres persistants", {timeout:90000}, async () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "frst-extensions-e2e-"));
    const project = path.join(dir, "project"); fs.mkdirSync(project);
    const harness = path.join(dir, "launch.cjs");
    fs.writeFileSync(harness, `
        const {app} = require('electron');
        app.setPath('userData', ${JSON.stringify(path.join(dir, "electron-data"))});
        global.qaRequire = require;
        const session = require(${JSON.stringify(path.join(root, "src/core/session"))});
        session.bootstrap = async () => ({ok:true});
        require(${JSON.stringify(path.join(root, "src/api/agents"))}).listAgents = async () => ({agents:[{id:-1002,name:'GPT 6 Luna'},{id:-1003,name:'GPT 6.1 Sol'}],source:'local'});
        const marketModule = require(${JSON.stringify(path.join(root, "desktop/marketplace"))});
        require(${JSON.stringify(path.join(root,"desktop/motion-marketplace"))}).downloadBundle=async()=>({content:'---\\nname: remotion-render\\ndescription: Render videos\\ndisabled: true\\napplication: code\\n---\\n\\nRead rules/render.md',files:[{path:'rules/render.md',data:Buffer.from('Render reference QA')}]});
        const original = marketModule.createMarketplace;
        marketModule.createMarketplace = options => original({...options, fetchFn:async url => {
            if (String(url).includes('raw.githubusercontent.com')) return new Response('---\\nname: community-qa\\ndescription: Communauté QA\\n---\\n\\nInstructions communautaires QA');
            const page = new URL(url).searchParams.get('page');
            return new Response(JSON.stringify({success:true,data:{skills:[{id:'remote-qa',name:'community-qa',author:'QA',description:'Une description QA',stars:123,githubUrl:'https://github.com/qa/test/tree/main/skill'}],pagination:{hasNext:page==='1'}}}), {headers:{'x-ratelimit-daily-remaining':'10'}});
        }});
        require(${JSON.stringify(path.join(root, "desktop/main.js"))});
    `);
    const env = {...process.env, FS_DATA_DIR:dir, FS_STATE_DIR:dir, FS_MCP_CONFIG:path.join(dir, "mcp.json"), FS_SKILLS_DIR:path.join(dir,"skills"), ELECTRON_DISABLE_SECURITY_WARNINGS:"1"};
    delete env.ELECTRON_RUN_AS_NODE;
    const app = await _electron.launch({executablePath:electron, args:[harness], cwd:root, env, timeout:30000});
    try {
        const page = await app.firstWindow();
        const errors = []; page.on("pageerror", error => errors.push(error.message));
        await page.waitForFunction(async () => (await window.frst.status()).booted);
        await page.evaluate(project => window.frst.openProject(project), project);
        await page.locator('[data-view="extensions"]').click();
        await page.waitForSelector('[data-library-id="web-quality"]');
        assert.equal(await page.locator("#library-list .center-card").count(), 22);
        await page.locator("#library-search").fill("interface");
        assert.equal(await page.locator("#library-list .center-card").count(), 1);
        await page.locator('[data-library-id="web-quality"]').getByRole("button", {name:"Voir les instructions"}).click();
        assert.match(await page.locator("#skill-editor-content").inputValue(), /responsive|composants/);
        assert.equal(await page.locator("#skill-editor-content").getAttribute("readonly"), "");
        await page.locator("#skill-editor-scope").selectOption("projet");
        await page.locator("#skill-editor-save").click();
        await page.waitForSelector("#skill-editor:not([open])", {state:"attached"});
        await page.locator('[data-center-tab="installed"]').click();
        const installed = page.locator('[data-skill-key="projet:web-quality"]');
        await installed.waitFor();
        await installed.getByRole("button", {name:/Ajouter aux favoris/}).click();
        await page.locator("#skills-filter").selectOption("favorites");
        assert.equal(await page.locator("#skills-list .center-card").count(), 1);
        await page.locator("#profile-save").click();
        await page.locator(".modal-overlay input").fill("Profil QA");
        await page.locator(".modal-overlay").getByRole("button", {name:"OK", exact:true}).click();
        await page.waitForFunction(() => document.getElementById("skill-profile").value === "Profil QA");
        await installed.getByRole("switch").uncheck();
        await page.waitForFunction(async () => (await window.frst.extensionAction("list")).skills[0].disabled);
        await page.locator("#profile-apply").click();
        await page.waitForFunction(async () => !(await window.frst.extensionAction("list")).skills[0].disabled);
        await installed.getByRole("button", {name:"Ouvrir", exact:true}).click();
        await page.locator("#skill-editor-content").fill("---\nname: web-quality\ndescription: Texte modifié QA\n---\n\nInstructions modifiées QA");
        await page.locator("#skill-editor-save").click();
        await page.waitForSelector("#skill-editor:not([open])", {state:"attached"});
        assert.match(fs.readFileSync(path.join(project,".frst/skills/web-quality/SKILL.md"),"utf8"), /Instructions modifiées QA/);
        if (process.env.FRST_QA_SCREENSHOT) await page.screenshot({path:process.env.FRST_QA_SCREENSHOT.replace(/\.png$/, "-skills.png")});
        await page.locator('[data-center-tab="motion"]').click();
        assert.equal(await page.locator("#motion-marketplace-list .center-card").count(),8);
        await page.locator("#motion-skill-scope").selectOption("projet");
        const titleSkill=page.locator('[data-motion-skill-id="motion-titles"]');
        await titleSkill.getByRole("button",{name:"Voir les instructions",exact:true}).click();
        assert.match(await page.locator("#skill-editor-content").inputValue(),/application: effectcraft/);
        await page.locator("#skill-editor-cancel").click();
        await titleSkill.getByRole("button",{name:"Installer",exact:true}).click();
        await titleSkill.getByRole("button",{name:"Installé",exact:true}).waitFor();
        assert.ok(fs.existsSync(path.join(project,".frst/skills/motion-titles/SKILL.md")));
        await page.locator('[data-motion-collection="code"]').click();
        assert.equal(await page.locator("#motion-marketplace-list .center-card").count(),5);
        assert.match(await page.locator("#motion-marketplace-note").innerText(),/ne pilotent pas EffectCraft/);
        if(process.env.FRST_QA_SCREENSHOT)await page.screenshot({path:process.env.FRST_QA_SCREENSHOT.replace(/\.png$/,"-motion-marketplace.png")});
        await page.locator('[data-motion-skill-id="remotion-render"]').getByRole("button",{name:"Lire et installer",exact:true}).click();
        await page.locator("#skill-editor[open]").waitFor();
        assert.match(await page.locator("#skill-editor-description").innerText(),/1 ressources annexes incluses/);
        await page.locator("#skill-editor-save").click();
        await page.locator("#skill-editor:not([open])").waitFor({state:"attached"});
        assert.equal(fs.readFileSync(path.join(project,".frst/skills/remotion-render/rules/render.md"),"utf8"),"Render reference QA");
        assert.match(fs.readFileSync(path.join(project,".frst/skills/remotion-render/SKILL.md"),"utf8"),/disabled: true/);
        await page.locator('[data-center-tab="marketplace"]').click();
        assert.equal(await page.locator("#motion-marketplace").isVisible(),false);
        await page.locator("#marketplace-query").fill("qa");
        await page.locator("#marketplace-search-button").click();
        await page.waitForSelector("#marketplace-results .center-card");
        await page.locator("#marketplace-next").click();
        await page.waitForFunction(() => document.getElementById("marketplace-page").textContent === "Page 2");
        await page.locator("#marketplace-results").getByRole("button", {name:"Lire et installer"}).click();
        await page.waitForSelector("#skill-editor[open]");
        assert.match(await page.locator("#skill-editor-content").inputValue(), /disabled: true/);
        await page.locator("#skill-editor-save").click();
        await page.waitForSelector("#skill-editor:not([open])", {state:"attached"});
        assert.equal((await page.evaluate(() => window.frst.extensionAction("list"))).skills.find(skill => skill.name === "community-qa").disabled, true);
        await page.locator('[data-center-tab="mcp"]').click();
        await page.locator("#btn-mcp-add").click();
        await page.locator("#mcp-name").fill("qa-local");
        await page.locator("#mcp-command").fill(process.execPath);
        await page.locator("#mcp-args").fill(JSON.stringify([path.join(root,"test/fixtures/fake-mcp-server.js")]));
        await page.locator("#mcp-editor-save").click();
        await page.waitForFunction(() => document.getElementById("mcp-list").textContent.includes("Connecté"));
        await page.locator("#mcp-list summary").click();
        assert.match(await page.locator("#mcp-list").innerText(), /echo/);
        await page.locator("#mcp-list").getByRole("button", {name:"Désactiver", exact:true}).click();
        await page.waitForFunction(() => document.getElementById("mcp-list").textContent.includes("Désactivé"));
        assert.equal(JSON.parse(fs.readFileSync(path.join(dir,"mcp.json"),"utf8")).mcpServers["qa-local"].disabled, true);
        await page.locator('[data-view="settings"]').click();
        await page.waitForFunction(() => document.getElementById("context-max-files").value === "500");
        await page.locator("#settings-search").fill("indexation");
        assert.equal(await page.locator("#settings-view .settings-card:visible").count(), 1);
        await page.locator('[data-context-preset="large"]').click();
        await page.locator("#settings-search").fill("");
        await page.locator("#settings-default-model").selectOption("-1003");
        await page.locator("#preferences-save").click();
        await page.waitForFunction(async () => (await window.frst.preferences()).contextMaxFiles === 3000);
        assert.equal((await page.evaluate(() => window.frst.preferences())).defaultModel, -1003);
        if (await app.evaluate(() => global.qaRequire("electron").safeStorage.isEncryptionAvailable())) {
            await page.locator("#settings-marketplace-key").fill("FAKE_SKILLSMP_KEY_QA");
            await page.locator("#marketplace-key-save").click();
            await page.waitForFunction(async () => (await window.frst.marketplaceKey()).configured);
            assert.equal(fs.readFileSync(path.join(dir,"skillsmp-key.enc")).includes(Buffer.from("FAKE_SKILLSMP_KEY_QA")), false);
            assert.equal(await page.locator("#settings-marketplace-key").inputValue(), "");
            await page.locator("#marketplace-key-clear").click();
            await page.waitForFunction(async () => !(await window.frst.marketplaceKey()).configured);
            assert.equal(fs.existsSync(path.join(dir,"skillsmp-key.enc")), false);
        }
        if (process.env.FRST_QA_SCREENSHOT) await page.screenshot({path:process.env.FRST_QA_SCREENSHOT.replace(/\.png$/, "-preferences.png")});
        await page.reload();
        await page.locator('[data-view="settings"]').click();
        await page.waitForFunction(() => document.getElementById("context-max-files").value === "3000");
        assert.deepEqual(errors, []);
    } finally { await app.close(); }
});
